let generatedWorkflowCount = 0;

export function createDemoWorkflow(
  zoneId: string,
  currentWorkflows: Workflow[],
): Workflow | null {
  const templates = DEMO_WORKFLOW_TEMPLATES[zoneId];
  if (!templates || templates.length === 0) return null;

  const zoneWorkflowCount = currentWorkflows.filter(
    (workflow) => workflow.zoneId === zoneId,
  ).length;
  const template =
    templates[(zoneWorkflowCount + generatedWorkflowCount) % templates.length];

  generatedWorkflowCount += 1;

  return {
    id: `wf-demo-${zoneId}-${Date.now()}-${generatedWorkflowCount}`,
    name: template.name,
    zoneId,
    status: "queued",
    progress: 0,
    assignedAgentId: null,
    priority: template.priority,
    skillIcon: template.skillIcon,
  };
}

export function trimCompletedWorkflows(
  workflows: Workflow[],
  maxCompletedPerZone = 4,
): Workflow[] {
  const keptCompletedCounts: Record<string, number> = {};

  return [...workflows]
    .reverse()
    .filter((workflow) => {
      if (workflow.status !== "completed") return true;

      const count = keptCompletedCounts[workflow.zoneId] ?? 0;
      if (count >= maxCompletedPerZone) return false;

      keptCompletedCounts[workflow.zoneId] = count + 1;
      return true;
    })
    .reverse();
}
